def generate_pdfs(policies):

    for _, policy in policies.iterrows():

        create_policy_pdf(policy)

    print(f"\nGenerated {len(policies)} Policy PDFs")

# ==========================================================
# VALIDATE PDFs
# ==========================================================

def validate_pdfs(policies):

    missing = []

    empty = []

    for _, policy in policies.iterrows():

        pdf = OUTPUT_FOLDER / f"{policy['Policy_Number']}.pdf"

        if not pdf.exists():
            missing.append(pdf.name)

        elif pdf.stat().st_size == 0:
            empty.append(pdf.name)

    print("\nValidation Report")
    print("-" * 40)

    print(f"Expected PDFs : {len(policies)}")
    print(f"Missing PDFs  : {len(missing)}")
    print(f"Empty PDFs    : {len(empty)}")

    if missing:
        print("\nMissing Files:")
        for f in missing:
            print(f" - {f}")

    if empty:
        print("\nEmpty Files:")
        for f in empty:
            print(f" - {f}")

# ==========================================================
# STATISTICS
# ==========================================================

def print_statistics(policies):

    print("\n" + "=" * 60)
    print("PDF GENERATION SUMMARY")
    print("=" * 60)

    print(f"Policies Loaded : {len(policies)}")
    print(f"PDFs Generated  : {len(list(OUTPUT_FOLDER.glob('*.pdf')))}")

    print("\nPolicy Types")

    print(policies["Policy_Type"].value_counts())

    print("\nInsurance Providers")

    print(policies["Insurance_Provider"].value_counts())

    print("=" * 60)


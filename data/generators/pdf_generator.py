from reportlab.pdfgen import canvas


def add_footer(canvas, doc):
    canvas.saveState()

    canvas.setFont("Helvetica", 8)

    canvas.drawString(
        40,
        20,
        "Generated by IntelliClaim AI | Confidential | Version 1.0"
    )

    canvas.restoreState()

